// Generates src/lib/api-schema.ts from the backend's OpenAPI contract
// (../cyber-redteam-foundry/openapi/v2.json): component schemas + route map.
// Dependency-free on purpose (openapi-typescript does not support TS 6 yet).
// `npm run gen:api` rewrites the file; src/lib/apiSchema.test.ts fails on drift.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SPEC = new URL('../../cyber-redteam-foundry/openapi/v2.json', import.meta.url)
const OUT = new URL('../src/lib/api-schema.ts', import.meta.url)

const q = s => JSON.stringify(s)

function ts(s) {
  if (!s || Object.keys(s).length === 0) return 'unknown'
  if (s.$ref) return `Schemas[${q(s.$ref.split('/').pop())}]`
  if (s.const !== undefined) return q(s.const)
  if (s.enum) return s.enum.map(q).join(' | ')
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(ts).join(' | ')
  if (s.allOf) return s.allOf.map(ts).join(' & ')
  switch (s.type) {
    case 'string': return 'string'
    case 'integer': case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': return `Array<${ts(s.items)}>`
    case 'object': {
      const props = s.properties ?? {}
      const req = new Set(s.required ?? [])
      const lines = Object.entries(props).map(([k, v]) => `${q(k)}${req.has(k) ? '' : '?'}: ${ts(v)}`)
      if (s.additionalProperties && typeof s.additionalProperties === 'object') lines.push(`[key: string]: ${ts(s.additionalProperties)}`)
      return lines.length ? `{ ${lines.join('; ')} }` : 'Record<string, unknown>'
    }
    default: return 'unknown'
  }
}

export function generate() {
  const spec = JSON.parse(readFileSync(SPEC, 'utf8'))
  const out = ['// GENERATED by scripts/gen-api-types.mjs from cyber-redteam-foundry/openapi/v2.json. Do not edit.', '']
  out.push('export interface Schemas {')
  for (const [name, schema] of Object.entries(spec.components.schemas).sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`  ${q(name)}: ${ts(schema)}`)
  }
  out.push('}', '', '/** Every `METHOD path` in the contract. */', 'export const ROUTES = [')
  const routes = []
  for (const [path, item] of Object.entries(spec.paths)) for (const method of Object.keys(item)) routes.push(`${method.toUpperCase()} ${path}`)
  for (const r of routes.sort()) out.push(`  ${q(r)},`)
  out.push('] as const', '')
  return out.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUT, generate())
